"""Pack the driver app files into base64 inside a Python module.

Render's Python runtime image does not include the frontend/ directory,
so the API cannot serve those files from disk in the cloud. This script
encodes them instead; main.py unpacks them to a temp dir at startup and
serves that. Run: python tools/pack_driver_app.py
"""
import base64
import os
import sys

SRC = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                   "frontend", "driver_app")
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                   "driver_app_payload.py")
FILES = ["index.html", "app.js", "sw.js", "icon.svg", "manifest.webmanifest"]


def main():
    parts = ['"""Generated by tools/pack_driver_app.py - do not edit."""\n',
             "import base64\n\nFILES = {\n"]
    for name in FILES:
        raw = open(os.path.join(SRC, name), "rb").read()
        enc = base64.b64encode(raw).decode()
        parts.append(f"    {name!r}: \"{enc}\",\n")
    parts.append("}\n")
    with open(OUT, "w") as fh:
        fh.write("".join(parts))
    print(f"wrote {OUT} ({sum(len(open(os.path.join(SRC, n), 'rb').read())
                             for n in FILES)} raw bytes)")


if __name__ == "__main__":
    sys.exit(main())
